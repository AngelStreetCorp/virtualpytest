#!/usr/bin/env bash
# Pin a host's USB capture + IR dongles to their physical USB port, so DEVICEn_* survive
# reboots and replugs. Guide: docs/agent/devices/PERSISTENT_DEVICES.md
#
#   pin_usb_ports.sh [--env FILE] N=PORT [N=PORT ...] [irN=PORT ...]
#
#   N=PORT    grabber of DEVICE<N> sits on USB port PORT (e.g. 3-1.4; see scripts/detect_grabber.sh)
#   irN=PORT  USB lirc IR dongle of DEVICE<N> sits on PORT (Pi hosts; /dev/lirc-stb<N>)
#   --env     also rewrite DEVICE<N>_VIDEO / _VIDEO_AUDIO / _IR_PATH in FILE (backup FILE.bak-<date>).
#             Only those keys are touched; the rest of the file stays as is.
#
# Names: video /dev/stb<N>, audio card id stb<N> (plughw:stb<N>,0), IR /dev/lirc-stb<N>.
# Needs root (writes /etc/udev/rules.d). Services are NOT restarted: restart vpt-stream/vpt-host yourself,
# only while every device of the host is idle.
set -euo pipefail
RULES=/etc/udev/rules.d/70-vpt-persistent.rules
ENVF=""
specs=()
while [ $# -gt 0 ]; do
  case "$1" in
    --env) ENVF="$2"; shift 2 ;;
    *=*) specs+=("$1"); shift ;;
    *) echo "usage: $0 [--env FILE] N=PORT [irN=PORT ...]" >&2; exit 2 ;;
  esac
done
[ ${#specs[@]} -gt 0 ] || { echo "no N=PORT given" >&2; exit 2; }

out="# Generated by pin_usb_ports.sh — USB port -> stable name. Guide: docs/agent/devices/PERSISTENT_DEVICES.md"$'\n'
for s in "${specs[@]}"; do
  k="${s%%=*}"; port="${s#*=}"
  [[ "$port" =~ ^[0-9]+-[0-9.]+$ ]] || { echo "bad port '$port' (want e.g. 3-1.4)" >&2; exit 2; }
  if [[ "$k" =~ ^ir([0-9]+)$ ]]; then
    n="${BASH_REMATCH[1]}"
    out+="SUBSYSTEM==\"lirc\", KERNELS==\"$port\", SYMLINK+=\"lirc-stb$n\""$'\n'
  elif [[ "$k" =~ ^[0-9]+$ ]]; then
    out+="SUBSYSTEM==\"video4linux\", KERNELS==\"$port\", ATTR{index}==\"0\", SYMLINK+=\"stb$k\""$'\n'
    out+="SUBSYSTEM==\"sound\", KERNEL==\"card*\", KERNELS==\"$port\", ATTR{id}=\"stb$k\""$'\n'
  else
    echo "bad key '$k'" >&2; exit 2
  fi
done
printf '%s' "$out" | sudo tee "$RULES" >/dev/null
sudo udevadm control --reload-rules
sudo udevadm trigger --subsystem-match=video4linux --subsystem-match=sound --subsystem-match=lirc
sudo udevadm settle || true
echo "Installed $RULES"; printf '%s' "$out"

if [ -n "$ENVF" ]; then
  cp "$ENVF" "$ENVF.bak-$(date +%Y%m%d)"
  for s in "${specs[@]}"; do
    k="${s%%=*}"
    if [[ "$k" =~ ^ir([0-9]+)$ ]]; then
      sed -i -E "s|^(DEVICE${BASH_REMATCH[1]}_IR_PATH=)[^ #]+|\1/dev/lirc-stb${BASH_REMATCH[1]}|" "$ENVF"
    else
      sed -i -E "s|^(DEVICE${k}_VIDEO=)/dev/video[0-9]+|\1/dev/stb${k}|; s|^(DEVICE${k}_VIDEO_AUDIO=)plughw:[0-9]*,[0-9]+|\1plughw:stb${k},0|" "$ENVF"
    fi
  done
  echo "Updated $ENVF (backup $ENVF.bak-$(date +%Y%m%d)); restart vpt-stream / vpt-host while the host is idle."
fi
