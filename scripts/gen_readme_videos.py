#!/usr/bin/env python3
"""
Regenerate the videos block of README.md and docs/videos/README.md from docs/videos/videos.json.

docs/videos/videos.json is the ONE data file for the videos: this script (GitHub surfaces) and the
app's Videos page (frontend VideoShowcase) both read it. Humans edit only that file: append the new
video to the TOP of "videos" (newest first), then run this script.

Only the text between `<!-- videos:start -->` and `<!-- videos:end -->` is rewritten, in both files.

Shape written in each block: the top (default) video, a 3-column row of the 3 newest videos (images only,
each with its publication number #N, oldest = 1; the title is in the link title/alt), and a
collapsible plain-text list of every video grouped by primary category (bold heading per category, alphabetical inside) (links only: no images, no embeds, so nothing extra loads).
GitHub cannot run JS, so the real dropdown that picks the top video exists only in the app
(frontend/src/components/docs/VideoShowcase.tsx); here the "All videos" list stands in for it.

Usage:
    python3 scripts/gen_readme_videos.py           # rewrite the blocks
    python3 scripts/gen_readme_videos.py --check   # CI: exit 1 if a block is stale
"""
import html
import json
import os
import re
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
DATA = os.path.join(REPO, "docs", "videos", "videos.json")
START, END = "<!-- videos:start -->", "<!-- videos:end -->"
NOTICE = "<!-- generated by scripts/gen_readme_videos.py from docs/videos/videos.json: edit the JSON, not this block -->"
NEWEST = 3

# (file, thumbnail style): README.md points at the committed thumbnail, docs/videos/README.md
# (which is not at the repo root) at the YouTube image.
TARGETS = [("README.md", "repo"), (os.path.join("docs", "videos", "README.md"), "youtube")]


def clean_title(t):
    return re.sub(r"\s*\|\s*VirtualPyTest\s*$", "", t or "").strip()


def url(v):
    return "https://www.youtube.com/watch?v=" + v["id"]


def thumb(v, style, hero=False):
    if style == "repo" and v.get("thumb"):
        return v["thumb"]
    return "https://img.youtube.com/vi/%s/%s.jpg" % (v["id"], "maxresdefault" if hero else "hqdefault")


def esc(s):
    return html.escape(s, quote=True)


def build_block(data, style):
    vids = data["videos"]
    by_id = {v["id"]: v for v in vids}
    top = by_id[data["default"]]
    newest = [v for v in vids if v["id"] != top["id"]][:NEWEST]

    n = len(vids)
    num = {v["id"]: n - i for i, v in enumerate(vids)}  # publication number: oldest = 1, newest = N

    t = clean_title(top["title"])
    lines = [
        NOTICE,
        '<div align="center">',
        '  <a href="%s" title="#%d %s">' % (url(top), num[top["id"]], esc(t)),
        '    <img src="%s" alt="#%d %s" width="100%%">' % (thumb(top, style, hero=True), num[top["id"]], esc(t)),
        "  </a>",
        "  <p><sub>#%d</sub></p>" % num[top["id"]],
        "</div>",
        "",
        '<table align="center">',
        "  <tr>",
    ]
    for v in newest:
        vt = clean_title(v["title"])
        lines += [
            '    <td align="center" width="33%">',
            '      <a href="%s" title="#%d %s"><img src="%s" alt="#%d %s" width="100%%"></a><br>'
            % (url(v), num[v["id"]], esc(vt), thumb(v, style), num[v["id"]], esc(vt)),
            "      <sub>#%d</sub>" % num[v["id"]],
            "    </td>",
        ]
    lines += [
        "  </tr>",
        "</table>",
        "",
        "<details>",
        "<summary>All videos (%d)</summary>" % len(vids),
        "",
    ]
    # Grouped by primary category (first of `categories`), groups in the fixed order of the JSON's
    # `categories` object; alphabetical inside a group like the app's dropdown; the number follows the title.
    for cat, label in data["categories"].items():
        group = [v for v in vids if v["categories"][0] == cat]
        if not group:
            continue
        lines += ["**%s**" % esc(label), ""]
        for v in sorted(group, key=lambda v: (clean_title(v["title"]).casefold(), v["id"])):
            lines.append("- [%s](%s) (#%d): %s" % (clean_title(v["title"]), url(v), num[v["id"]], v["summary"]))
        lines.append("")
    lines.pop()
    lines += ["", "</details>"]
    return "\n".join(lines)


def rewrite(text, block, name):
    if START not in text or END not in text:
        sys.exit("%s: markers %s ... %s not found" % (name, START, END))
    pre, rest = text.split(START, 1)
    _, post = rest.split(END, 1)
    return pre + START + "\n" + block + "\n" + END + post


def main():
    check = "--check" in sys.argv
    with open(DATA, encoding="utf-8") as f:
        data = json.load(f)
    ids = [v["id"] for v in data["videos"]]
    if len(set(ids)) != len(ids):
        sys.exit("videos.json: duplicate id")
    if data["default"] not in ids:
        sys.exit("videos.json: default id %s is not in videos" % data["default"])
    cats = data.get("categories")
    if not isinstance(cats, dict) or not cats:
        sys.exit("videos.json: top-level `categories` (key -> label) is missing")
    for v in data["videos"]:
        c = v.get("categories")
        if not c:
            sys.exit("videos.json: video %s has no `categories` (pick 1-2 of: %s)" % (v["id"], ", ".join(cats)))
        bad = [x for x in c if x not in cats]
        if bad:
            sys.exit("videos.json: video %s has unknown category %s (allowed: %s)" % (v["id"], ", ".join(bad), ", ".join(cats)))
    stale = []
    for rel, style in TARGETS:
        path = os.path.join(REPO, rel)
        with open(path, encoding="utf-8") as f:
            old = f.read()
        new = rewrite(old, build_block(data, style), rel)
        if new != old:
            stale.append(rel)
            if not check:
                with open(path, "w", encoding="utf-8") as f:
                    f.write(new)
    if check:
        if stale:
            print("STALE: run python3 scripts/gen_readme_videos.py  (" + ", ".join(stale) + ")")
            sys.exit(1)
        print("videos blocks up to date")
    else:
        print("rewrote: " + (", ".join(stale) if stale else "nothing (already up to date)"))


if __name__ == "__main__":
    main()
