#!/usr/bin/env python3
"""Write the list of published API specs that the in-app reference offers.

The API reference used to hard-code 14 spec filenames in the component, so a
new spec was never offered to a developer (BUG-0800). The list is built from
the files in ``docs/api/specs/`` instead, with the label each spec gives
itself in ``info.title``.

The two bulk route dumps stay out of the dropdown: they are inventories of
every registered route, not a category a developer integrates against.

    python3 scripts/generate_api_spec_manifest.py           # write the file
    python3 scripts/generate_api_spec_manifest.py --check   # fail if stale

Run it after adding or removing a spec, and after renaming one.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SPECS_DIR = ROOT / "docs" / "api" / "specs"
TARGET = ROOT / "frontend" / "src" / "config" / "apiSpecs.ts"

# Inventories of every registered route, not categories: not offered.
BULK_DUMPS = ("server-additional-routes", "host-backend-host-routes")

HEADER = """// Generated by scripts/generate_api_spec_manifest.py — do not edit by hand.
// The list of published OpenAPI specs under docs/api/specs/ that the API
// reference offers. Run the script again after adding, renaming or removing
// a spec.

export interface ApiSpecEntry {
  /** The file name under docs/api/specs/, without the .yaml suffix. */
  filename: string;
  /** The label in the "Select API" dropdown. */
  title: string;
}

export const API_SPECS: ApiSpecEntry[] = [
"""


def spec_title(path: Path) -> str:
    """The label the spec gives itself; the file name when it gives none."""
    with path.open(encoding="utf-8") as handle:
        document = yaml.safe_load(handle) or {}
    title = (document.get("info") or {}).get("title")
    return title.strip() if isinstance(title, str) and title.strip() else path.stem


def entries() -> list[dict[str, str]]:
    """Every spec that belongs in the dropdown, in file-name order."""
    found = []
    for path in sorted(SPECS_DIR.glob("*.yaml")):
        if path.stem in BULK_DUMPS:
            continue
        found.append({"filename": path.stem, "title": spec_title(path)})
    return found


def render(items: list[dict[str, str]]) -> str:
    lines = [HEADER]
    for item in items:
        lines.append(f"  {{ filename: '{item['filename']}', title: '{item['title']}' }},\n")
    lines.append("];\n")
    return "".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when the file is stale")
    args = parser.parse_args()

    if not SPECS_DIR.is_dir():
        print(f"no spec folder at {SPECS_DIR}", file=sys.stderr)
        return 1

    wanted = render(entries())
    current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""

    if args.check:
        if current != wanted:
            print(f"{TARGET} is stale — run: python3 scripts/generate_api_spec_manifest.py", file=sys.stderr)
            return 1
        print(f"{TARGET.relative_to(ROOT)} is up to date ({len(entries())} specs)")
        return 0

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(wanted, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)} ({len(entries())} specs)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
