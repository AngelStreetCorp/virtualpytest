#!/usr/bin/env python3
"""
Regenerate the screenshot grid of docs/screenshots/README.md from docs/screenshots/screenshots.json.

docs/screenshots/screenshots.json is the ONE data file for the screenshots: this script (GitHub view) and
the app's Screenshots page (frontend ScreenshotGallery) both read it. Humans edit only that file: add the
entry (id = file stem, title, file, categories: 1-2 of the top-level `categories`, the first is the primary
one), then run this script.

Only the text between `<!-- screenshots:start -->` and `<!-- screenshots:end -->` is rewritten. The
screenshots are grouped by PRIMARY category (bold heading per category, in the order of the JSON's
`categories` object), alphabetical by title inside a group, as a 3-column `<table>` of thumbnails
(thumb in <img src>, full file in <a href>).

It fails (exit 1, with the reason) on an unknown category, a screenshot without categories, a duplicate id
or a missing .webp / .thumb.webp in frontend/public/screenshot/.

Usage:
    python3 scripts/gen_readme_screenshots.py           # rewrite the block
    python3 scripts/gen_readme_screenshots.py --check   # CI: exit 1 if the block is stale
"""
import html
import json
import os
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
DATA = os.path.join(REPO, "docs", "screenshots", "screenshots.json")
README = os.path.join(REPO, "docs", "screenshots", "README.md")
IMG_DIR = os.path.join(REPO, "frontend", "public", "screenshot")
START, END = "<!-- screenshots:start -->", "<!-- screenshots:end -->"
NOTICE = "<!-- generated by scripts/gen_readme_screenshots.py from docs/screenshots/screenshots.json: edit the JSON, not this block -->"
REL = "../../frontend/public/screenshot"
COLUMNS = 3


def esc(s):
    return html.escape(s, quote=True)


def validate(data):
    cats = data.get("categories")
    if not isinstance(cats, dict) or not cats:
        sys.exit("screenshots.json: top-level `categories` (key -> label) is missing")
    seen = set()
    for s in data["screenshots"]:
        sid = s.get("id")
        if not sid or not s.get("title") or not s.get("file"):
            sys.exit("screenshots.json: an entry needs id, title and file: %r" % (s,))
        if sid in seen:
            sys.exit("screenshots.json: duplicate id %s" % sid)
        seen.add(sid)
        c = s.get("categories")
        if not c:
            sys.exit("screenshots.json: screenshot %s has no `categories` (pick 1-2 of: %s)" % (sid, ", ".join(cats)))
        bad = [x for x in c if x not in cats]
        if bad:
            sys.exit("screenshots.json: screenshot %s has unknown category %s (allowed: %s)" % (sid, ", ".join(bad), ", ".join(cats)))
        for suffix in (".webp", ".thumb.webp"):
            if not os.path.isfile(os.path.join(IMG_DIR, s["file"] + suffix)):
                sys.exit("screenshots.json: screenshot %s: frontend/public/screenshot/%s%s is missing (run scripts/screenshot_to_webp.py)" % (sid, s["file"], suffix))


def cell(s):
    alt = esc(s.get("alt") or s["title"])
    return [
        '    <td align="center" width="250">',
        "      <b>%s</b>" % esc(s["title"]),
        '      <a href="%s/%s.webp" target="_blank">' % (REL, s["file"]),
        '        <img src="%s/%s.thumb.webp" width="240" alt="%s">' % (REL, s["file"], alt),
        "      </a>",
        "    </td>",
    ]


def build_block(data):
    lines = [NOTICE]
    first = True
    for cat, label in data["categories"].items():
        group = [s for s in data["screenshots"] if s["categories"][0] == cat]
        if not group:
            continue
        group.sort(key=lambda s: (s["title"].casefold(), s["id"]))
        if not first:
            lines.append("")
        first = False
        lines += ["**%s**" % esc(label), "", "<table>"]
        for i in range(0, len(group), COLUMNS):
            lines.append("  <tr>")
            row = group[i:i + COLUMNS]
            for s in row:
                lines += cell(s)
            for _ in range(COLUMNS - len(row)):
                lines += ['    <td align="center" width="250">', "    </td>"]
            lines.append("  </tr>")
        lines.append("</table>")
    return "\n".join(lines)


def rewrite(text, block, name):
    if START not in text or END not in text:
        sys.exit("%s: markers %s ... %s not found" % (name, START, END))
    pre, rest = text.split(START, 1)
    _, post = rest.split(END, 1)
    return pre + START + "\n" + block + "\n" + END + post


def main():
    check = "--check" in sys.argv
    with open(DATA, encoding="utf-8") as f:
        data = json.load(f)
    validate(data)
    with open(README, encoding="utf-8") as f:
        old = f.read()
    new = rewrite(old, build_block(data), "docs/screenshots/README.md")
    if check:
        if new != old:
            print("STALE: run python3 scripts/gen_readme_screenshots.py  (docs/screenshots/README.md)")
            sys.exit(1)
        print("screenshots block up to date")
    elif new != old:
        with open(README, "w", encoding="utf-8") as f:
            f.write(new)
        print("rewrote: docs/screenshots/README.md")
    else:
        print("rewrote: nothing (already up to date)")


if __name__ == "__main__":
    main()
